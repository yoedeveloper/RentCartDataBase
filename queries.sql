--tabla vehiculo
CREATE TABLE IF NOT EXISTS VEHICULO(
    ID_VEHICULO INTEGER PRIMARY KEY,
    MARCA_NOMBRE TEXT NOT NULL,
    PLACA TEXT NOT NULL,
    LANZAMIENTO TEXT NOT NULL,
    TIPO TEXT NOT NULL
);
-- TABLA CLIENTE 
CREATE TABLE IF NOT EXISTS CLIENTE(
ID_CLIENTE INTEGER PRIMARY KEY,
NOMBRE TEXT NOT NULL,
APELLIDO TEXT NOT NULL,
FECHA_RENTA TEXT NOT NULL
);

--TABLA VEHICULO_CLIENTE
CREATE TABLE IF NOT EXISTS VEHICULO_CLIENTE(
    VEHICULO_ID INTEGER NOT NULL,
    CLIENTE_ID INTEGER NOT NULL,
    FOREIGN KEY(VEHICULO_ID) REFERENCES VEHICULO(ID_VEHICULO),
    FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID_CLIENTE),
    PRIMARY KEY (VEHICULO_ID, CLIENTE_ID)
);
